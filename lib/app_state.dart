// กลไกแจ้งเตือนให้ทุกหน้าจอโหลดข้อมูลใหม่ เมื่อฐานข้อมูลถูกแก้ไข
//
// เหตุผลที่ไม่ใช้ Provider หรือ Riverpod: แอปนี้มีสถานะร่วมเพียงอย่างเดียวคือ
// "ข้อมูลในฐานข้อมูลเปลี่ยนไปแล้วนะ" การใช้ ValueNotifier ตัวเดียวคู่กับ
// ValueListenableBuilder จึงเพียงพอ และไม่ต้องพึ่งไลบรารีภายนอกเพิ่ม
import 'package:flutter/foundation.dart';

/// ตัวนับรุ่นของข้อมูล ทุกครั้งที่ค่าเปลี่ยน หน้าจอที่ฟังอยู่จะ build ใหม่
/// แล้วดึงข้อมูลจากฐานข้อมูลรอบใหม่ผ่าน FutureBuilder
final ValueNotifier<int> dbRevision = ValueNotifier<int>(0);

/// เรียกทุกครั้งหลังเพิ่ม แก้ไข หรือลบข้อมูลสำเร็จ
/// ค่าที่เพิ่มขึ้นไม่มีความหมายในตัวเอง ใช้เป็นสัญญาณให้ทุกหน้ารีเฟรชเท่านั้น
void notifyDbChanged() => dbRevision.value++;
